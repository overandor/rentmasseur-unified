# ─── Frozen Tokenizer Standard ────────────────────────────

TOKENIZER_VERSION = "frozen-v1.0"
TOKENIZER_DELIMITERS = re.compile(
    r'[ \t\n\r\f\v]+|'      # whitespace
    r'(?<=[a-z])(?=[A-Z])|' # camelCase boundaries
    r'(?<=[A-Z])(?=[A-Z][a-z])|' # ABBRWord boundaries
    r'[(){}\[\];,.<>:=+\-*/%&|^~!?@#\'"\\`]'  # operators/punctuation
)

def tokenize_source(source: str) -> List[str]:
    """Frozen tokenizer: deterministic, language-agnostic token splitting."""
    raw = TOKENIZER_DELIMITERS.split(source)
    return [t for t in raw if t]

def count_tokens(source: str) -> int:
    return len(tokenize_source(source))

