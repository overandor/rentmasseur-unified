#!/usr/bin/env python3
"""Point-in-Time Code-Capital Underwriting Scanner.

Measures startup technical substance relative to invested capital at
a financing event. Produces an auditable, point-in-time report with
evidence hashes, eligibility filtering, capital normalization, physical
code measurements, haircuts, and a final underwriting statement.

Usage:
  python3 underwriter.py scan <repo_path> [--capital $3000000] [--date 2026-07-10]
  python3 underwriter.py report <scan_json>
  python3 underwriter.py demo
"""
